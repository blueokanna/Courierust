//! Build-time protobuf + gRPC code generator (zero dependencies).
//!
//! Scans `proto/*.proto` at build time and generates idiomatic Rust
//! (structs + wire codecs + typed gRPC client stubs) into
//! `OUT_DIR/courierust_generated.rs`, which the crate re-exports as
//! `courierust::courierust_grpc::generated`.
//!
//! Supported proto subset:
//!   * `syntax = "proto3";` and `package foo.bar;` (package -> module
//!     nesting)
//!   * `message` with scalar fields (`string bytes bool int32 int64
//!     uint32 uint64 sint32 sint64 fixed32 fixed64 float double`),
//!     `repeated <scalar>`, message-typed fields and `repeated
//!     <Message>`; `//` line comments and `/* */` block comments
//!   * `service` with unary and server-streaming `rpc` methods
//!
//! Field numbers are validated (1..=2^29-1, unique per message). The
//! generated code compiles against the crate's own wire codec
//! (`courierust_grpc::proto`) — no prost, no syn, no third-party crate.

use std::env;
use std::fs;
use std::path::Path;

fn main() {
    println!("cargo:rerun-if-changed=proto");
    let out_dir = env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    let proto_dir = Path::new(env!("CARGO_MANIFEST_DIR")).join("proto");
    let mut generated = String::from(
        "// @generated by build.rs from proto/*.proto — do not edit by hand.\n\
         // Uses the crate's own protobuf wire codec; no third-party crates.\n\n",
    );
    if proto_dir.is_dir() {
        let mut entries: Vec<_> = fs::read_dir(&proto_dir)
            .expect("read proto dir")
            .filter_map(|e| e.ok())
            .filter(|e| e.path().extension().map(|x| x == "proto").unwrap_or(false))
            .collect();
        entries.sort_by_key(|e| e.file_name());
        for entry in entries {
            let text = fs::read_to_string(entry.path()).expect("read proto file");
            match parse_proto(&text) {
                Ok(file) => generate_file(&mut generated, &file),
                Err(error) => panic!("failed to parse {}: {error}", entry.path().display()),
            }
        }
    }
    let out_path = Path::new(&out_dir).join("courierust_generated.rs");
    fs::write(&out_path, &generated).expect("write generated code");
}

// ---------------------------------------------------------------------
// Proto model
// ---------------------------------------------------------------------

#[derive(Debug, Clone, PartialEq)]
enum FieldType {
    Scalar(&'static str),
    Repeated(&'static str),
    Message(String),
    RepeatedMessage(String),
}

#[derive(Debug)]
struct Field {
    number: u32,
    name: String,
    ty: FieldType,
}

#[derive(Debug)]
struct Message {
    name: String,
    fields: Vec<Field>,
}

#[derive(Debug)]
struct Rpc {
    name: String,
    request: String,
    response: String,
    server_streaming: bool,
}

#[derive(Debug)]
struct Service {
    name: String,
    rpcs: Vec<Rpc>,
}

#[derive(Debug, Default)]
struct ProtoFile {
    package: Option<String>,
    messages: Vec<Message>,
    services: Vec<Service>,
}

// ---------------------------------------------------------------------
// Parser (a small, strict tokenizer for the supported subset)
// ---------------------------------------------------------------------

fn parse_proto(text: &str) -> Result<ProtoFile, String> {
    let mut tokens = tokenize(text)?;
    let mut file = ProtoFile::default();
    while !tokens.is_empty() && !matches!(tokens.first(), Some(Token::Eof)) {
        let (keyword, semicolon) = match tokens.remove(0) {
            Token::Ident(s) => (s, false),
            Token::Semicolon => (String::new(), true),
            other => return Err(format!("expected identifier, got {other:?}")),
        };
        if semicolon {
            continue;
        }
        match keyword.as_str() {
            "syntax" => {
                expect(&mut tokens, Token::Eq, "syntax =")?;
                tokens.remove(0); // the quoted string
                expect(&mut tokens, Token::Semicolon, "syntax ;")?;
            }
            "package" => {
                let mut parts = Vec::new();
                loop {
                    match tokens.remove(0) {
                        Token::Ident(s) => parts.push(s),
                        Token::Dot => {}
                        Token::Semicolon => break,
                        other => return Err(format!("bad package: {other:?}")),
                    }
                }
                file.package = Some(parts.join("."));
            }
            "message" => {
                let name = expect_ident(&mut tokens, "message name")?;
                expect(&mut tokens, Token::LBrace, "message {")?;
                let mut fields = Vec::new();
                loop {
                    match tokens.remove(0) {
                        Token::RBrace => break,
                        Token::Ident(leading) => {
                            // repeated? then the actual type
                            let mut ty_name = leading;
                            let mut repeated = false;
                            if ty_name == "repeated" {
                                repeated = true;
                                ty_name = expect_ident(&mut tokens, "repeated type")?;
                            }
                            let field_name = expect_ident(&mut tokens, "field name")?;
                            expect(&mut tokens, Token::Eq, "field =")?;
                            let number = expect_u32(&mut tokens, "field number")?;
                            if number == 0 || number >= (1 << 29) {
                                return Err(format!("invalid field number {number} in {name}"));
                            }
                            if fields.iter().any(|f: &Field| f.number == number) {
                                return Err(format!(
                                    "duplicate field number {number} in message {name}"
                                ));
                            }
                            expect(&mut tokens, Token::Semicolon, "field ;")?;
                            let ty = if let Some(scalar) = scalar_of(&ty_name) {
                                if repeated {
                                    FieldType::Repeated(scalar)
                                } else {
                                    FieldType::Scalar(scalar)
                                }
                            } else if repeated {
                                FieldType::RepeatedMessage(ty_name)
                            } else {
                                FieldType::Message(ty_name)
                            };
                            fields.push(Field {
                                number,
                                name: field_name,
                                ty,
                            });
                        }
                        other => return Err(format!("bad field: {other:?}")),
                    }
                }
                file.messages.push(Message { name, fields });
            }
            "service" => {
                let name = expect_ident(&mut tokens, "service name")?;
                expect(&mut tokens, Token::LBrace, "service {")?;
                let mut rpcs = Vec::new();
                loop {
                    match tokens.remove(0) {
                        Token::RBrace => break,
                        Token::Ident(word) if word == "rpc" => {
                            let rpc_name = expect_ident(&mut tokens, "rpc name")?;
                            expect(&mut tokens, Token::LParen, "rpc (")?;
                            let request = expect_ident(&mut tokens, "request type")?;
                            expect(&mut tokens, Token::RParen, "rpc )")?;
                            expect(&mut tokens, Token::Ident("returns".to_owned()), "returns")?;
                            expect(&mut tokens, Token::LParen, "returns (")?;
                            let mut server_streaming = false;
                            if matches!(tokens.first(), Some(Token::Ident(w)) if w == "stream") {
                                tokens.remove(0);
                                server_streaming = true;
                            }
                            let response = expect_ident(&mut tokens, "response type")?;
                            expect(&mut tokens, Token::RParen, "returns )")?;
                            expect(&mut tokens, Token::Semicolon, "rpc ;")?;
                            rpcs.push(Rpc {
                                name: rpc_name,
                                request,
                                response,
                                server_streaming,
                            });
                        }
                        other => return Err(format!("bad service item: {other:?}")),
                    }
                }
                file.services.push(Service { name, rpcs });
            }
            "option" | "import" => {
                // Skip to the terminating semicolon (imports and options
                // are not needed by the generator).
                loop {
                    match tokens.remove(0) {
                        Token::Semicolon => break,
                        Token::Eof => return Err("unterminated option/import".to_string()),
                        _ => {}
                    }
                }
            }
            other => return Err(format!("unsupported proto keyword: {other}")),
        }
    }
    Ok(file)
}

fn scalar_of(name: &str) -> Option<&'static str> {
    Some(match name {
        "string" => "string",
        "bytes" => "bytes",
        "bool" => "bool",
        "int32" => "int32",
        "int64" => "int64",
        "uint32" => "uint32",
        "uint64" => "uint64",
        "sint32" => "sint32",
        "sint64" => "sint64",
        "fixed32" => "fixed32",
        "fixed64" => "fixed64",
        "float" => "float",
        "double" => "double",
        _ => return None,
    })
}

// ---------------------------------------------------------------------
// Tokenizer
// ---------------------------------------------------------------------

#[derive(Debug, Clone, PartialEq)]
enum Token {
    Ident(String),
    Eq,
    Dot,
    Semicolon,
    LBrace,
    RBrace,
    LParen,
    RParen,
    /// A quoted string (kept verbatim, including quotes).
    Quoted(String),
    Number(u32),
    Eof,
}

fn tokenize(text: &str) -> Result<Vec<Token>, String> {
    let bytes = text.as_bytes();
    let mut tokens = Vec::new();
    let mut i = 0usize;
    while i < bytes.len() {
        let c = bytes[i] as char;
        if c.is_whitespace() {
            i += 1;
            continue;
        }
        if c == '/' && i + 1 < bytes.len() && bytes[i + 1] as char == '/' {
            while i < bytes.len() && bytes[i] as char != '\n' {
                i += 1;
            }
            continue;
        }
        if c == '/' && i + 1 < bytes.len() && bytes[i + 1] as char == '*' {
            let end = text[i + 2..]
                .find("*/")
                .ok_or_else(|| "unterminated block comment".to_string())?;
            i += 2 + end + 2;
            continue;
        }
        match c {
            '=' => {
                tokens.push(Token::Eq);
                i += 1;
            }
            '.' => {
                tokens.push(Token::Dot);
                i += 1;
            }
            ';' => {
                tokens.push(Token::Semicolon);
                i += 1;
            }
            '{' => {
                tokens.push(Token::LBrace);
                i += 1;
            }
            '}' => {
                tokens.push(Token::RBrace);
                i += 1;
            }
            '(' => {
                tokens.push(Token::LParen);
                i += 1;
            }
            ')' => {
                tokens.push(Token::RParen);
                i += 1;
            }
            '"' | '\'' => {
                let quote = c;
                let start = i + 1;
                let mut end = start;
                while end < bytes.len() && bytes[end] as char != quote {
                    end += 1;
                }
                if end >= bytes.len() {
                    return Err("unterminated string literal".to_string());
                }
                tokens.push(Token::Quoted(text[start..end].to_string()));
                i = end + 1;
            }
            '0'..='9' => {
                let start = i;
                while i < bytes.len() && (bytes[i] as char).is_ascii_digit() {
                    i += 1;
                }
                let value: u32 = text[start..i]
                    .parse()
                    .map_err(|_| "invalid field number".to_string())?;
                tokens.push(Token::Number(value));
            }
            c if c.is_alphabetic() || c == '_' => {
                let start = i;
                while i < bytes.len()
                    && (bytes[i] as char == '_' || (bytes[i] as char).is_alphanumeric())
                {
                    i += 1;
                }
                tokens.push(Token::Ident(text[start..i].to_string()));
            }
            other => return Err(format!("unexpected character `{other}`")),
        }
    }
    tokens.push(Token::Eof);
    Ok(tokens)
}

fn expect(tokens: &mut Vec<Token>, expected: Token, what: &str) -> Result<(), String> {
    if tokens.is_empty() {
        return Err(format!("unexpected end of file while parsing {what}"));
    }
    let actual = tokens.remove(0);
    if actual == expected {
        Ok(())
    } else {
        Err(format!("expected {what}, got {actual:?}"))
    }
}

fn expect_ident(tokens: &mut Vec<Token>, what: &str) -> Result<String, String> {
    match tokens.remove(0) {
        Token::Ident(s) => Ok(s),
        other => Err(format!("expected {what}, got {other:?}")),
    }
}

fn expect_u32(tokens: &mut Vec<Token>, what: &str) -> Result<u32, String> {
    match tokens.remove(0) {
        Token::Number(n) => Ok(n),
        other => Err(format!("expected {what}, got {other:?}")),
    }
}

