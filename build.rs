fn to_snake(name: &str) -> String {
    let mut out = String::new();
    for (i, c) in name.chars().enumerate() {
        if c.is_uppercase() {
            if i > 0 {
                out.push('_');
            }
            out.push(c.to_ascii_lowercase());
        } else {
            out.push(c);
        }
    }
    out
}

fn rust_scalar(name: &str) -> &'static str {
    match name {
        "string" => "alloc::string::String",
        "bytes" => "alloc::vec::Vec<u8>",
        "bool" => "bool",
        "int32" | "sint32" => "i32",
        "int64" | "sint64" => "i64",
        "uint32" | "fixed32" => "u32",
        "uint64" | "fixed64" => "u64",
        "float" => "f32",
        "double" => "f64",
        _ => unreachable!("scalar"),
    }
}

fn rust_scalar_f32_f64(name: &str) -> &'static str {
    rust_scalar(name)
}

fn generate_file(out: &mut String, file: &ProtoFile) {
    // Nest under the package, if any.
    if let Some(package) = &file.package {
        let parts: Vec<&str> = package.split('.').collect();
        let mut full_pkg = String::new();
        for (i, part) in parts.iter().enumerate() {
            if i > 0 {
                full_pkg.push('.');
            }
            full_pkg.push_str(part);
        }
        for part in &parts {
            out.push_str(&format!(
                "/// Proto package `{full_pkg}` (generated).\npub mod {part} {{\n"
            ));
        }
        out.push_str("    use crate::courierust_grpc::proto;\n");
        out.push_str("    use crate::courierust_grpc::proto::ProtoMessage;\n");
        out.push_str("    use crate::courierust_grpc::codec;\n");
        out.push_str("    use crate::courierust_error::{Error, Result};\n");
        for message in &file.messages {
            generate_message(out, message, 1);
        }
        for service in &file.services {
            generate_service(out, service, 1, file.package.as_deref());
        }
        for _ in &parts {
            out.push_str("}\n");
        }
    } else {
        out.push_str("use crate::courierust_grpc::proto;\n");
        out.push_str("use crate::courierust_grpc::proto::ProtoMessage;\n");
        out.push_str("use crate::courierust_grpc::codec;\n");
        out.push_str("use crate::courierust_error::{Error, Result};\n");
        for message in &file.messages {
            generate_message(out, message, 0);
        }
        for service in &file.services {
            generate_service(out, service, 0, file.package.as_deref());
        }
    }
}

fn indent(level: usize) -> String {
    "    ".repeat(level)
}

/// The wire "kind" used in helper names for a scalar (distinct from the
/// proto type name, which also covers `string`/`bytes`).
fn scalar_kind(name: &str) -> &'static str {
    match name {
        "bool" => "bool",
        "int32" => "i32",
        "int64" => "i64",
        "uint32" => "u32",
        "uint64" => "u64",
        "sint32" => "s32",
        "sint64" => "s64",
        "fixed32" => "fixed32",
        "fixed64" => "fixed64",
        "float" => "float",
        "double" => "double",
        _ => unreachable!("{name} is not a scalar"),
    }
}

/// Whether a scalar is length-delimited (`string`/`bytes`).
fn is_length_delimited(name: &str) -> bool {
    name == "string" || name == "bytes"
}

fn generate_message(out: &mut String, message: &Message, level: usize) {
    let ind = indent(level);
    // Struct.
    out.push_str(&format!(
        "\n{ind}/// Message `{}` (proto3).\n",
        message.name
    ));
    out.push_str(&format!(
        "{ind}#[derive(Debug, Clone, PartialEq, Default)]\n"
    ));
    out.push_str(&format!("{ind}pub struct {} {{\n", message.name));
    for field in &message.fields {
        let rust_ty = match &field.ty {
            FieldType::Scalar(s) => rust_scalar_f32_f64(s).to_string(),
            FieldType::Repeated(s) => {
                format!("alloc::vec::Vec<{}>", rust_scalar_f32_f64(s))
            }
            FieldType::Message(m) => format!("::core::option::Option<{m}>"),
            FieldType::RepeatedMessage(m) => format!("alloc::vec::Vec<{m}>"),
        };
        out.push_str(&format!(
            "{ind}    /// Field {} (`{}`).\n",
            field.number, field.name
        ));
        out.push_str(&format!("{ind}    pub {}: {rust_ty},\n", field.name));
    }
    out.push_str(&format!("{ind}}}\n"));

    // ProtoMessage encode.
    out.push_str(&format!(
        "\n{ind}impl proto::ProtoMessage for {} {{\n",
        message.name
    ));
    out.push_str(&format!(
        "{ind}    fn encode_message_body(&self, out: &mut alloc::vec::Vec<u8>) {{\n"
    ));
    for field in &message.fields {
        let e = indent(level + 2);
        let n = field.number;
        match &field.ty {
            FieldType::Scalar(s) => {
                // string/bytes are passed by reference; Copy scalars by
                // value (the Encoder mirrors the wire type).
                let expr = if is_length_delimited(s) {
                    format!("&self.{}", field.name)
                } else {
                    format!("self.{}", field.name)
                };
                out.push_str(&format!("{e}proto::Encoder::{s}(out, {n}, {expr});\n"));
            }
            FieldType::Message(m) => out.push_str(&format!(
                "{e}if let Some(value) = &self.{} {{ proto::Encoder::message::<{m}>(out, {n}, value); }}\n",
                field.name
            )),
            FieldType::Repeated(s) if is_length_delimited(s) => out.push_str(&format!(
                "{e}for value in &self.{} {{ proto::Encoder::{s}(out, {n}, value); }}\n",
                field.name
            )),
            FieldType::Repeated(s) => {
                let kind = scalar_kind(s);
                out.push_str(&format!(
                    "{e}if !self.{}.is_empty() {{\n\
                     {e}    let mut payload = alloc::vec::Vec::new();\n\
                     {e}    for value in &self.{} {{ proto::push_packed_{kind}(&mut payload, *value); }}\n\
                     {e}    proto::encode_packed_payload(out, {n}, &payload);\n\
                     {e}}}\n",
                    field.name, field.name
                ));
            }
            FieldType::RepeatedMessage(m) => out.push_str(&format!(
                "{e}for value in &self.{} {{ proto::Encoder::message::<{m}>(out, {n}, value); }}\n",
                field.name
            )),
        }
    }
    out.push_str(&format!("{ind}    }}\n"));

    // ProtoMessage decode.
    out.push_str(&format!(
        "{ind}    fn decode_message_body(buf: &[u8]) -> Result<Self> {{\n"
    ));
    out.push_str(&format!("{ind}        let mut result = Self::default();\n"));
    out.push_str(&format!(
        "{ind}        let mut reader = proto::SliceReader::new(buf);\n"
    ));
    out.push_str(&format!("{ind}        while reader.remaining() > 0 {{\n"));
    out.push_str(&format!(
        "{ind}            proto::Decoder::field(&mut reader, |number, wire, value, payload| {{\n"
    ));
    out.push_str(&format!("{ind}                let _ = value;\n"));
    out.push_str(&format!("{ind}                match (number, wire) {{\n"));
    for field in &message.fields {
        let e = indent(level + 4);
        let n = field.number;
        let f = &field.name;
        match &field.ty {
            FieldType::Scalar(s) => {
                if is_length_delimited(s) {
                    if *s == "string" {
                        out.push_str(&format!(
                            "{e}({n}, proto::WireType::LengthDelimited) => {{\n\
                             {e}    result.{f} = ::core::str::from_utf8(payload)\n\
                             {e}        .map_err(|_| Error::protocol(\"invalid utf8 in protobuf string\"))?\n\
                             {e}        .to_string();\n\
                             {e}}}\n"
                        ));
                    } else {
                        out.push_str(&format!(
                            "{e}({n}, proto::WireType::LengthDelimited) => {{\n\
                             {e}    result.{f} = payload.to_vec();\n\
                             {e}}}\n"
                        ));
                    }
                } else {
                    let wire = match *s {
                        "fixed32" | "float" => "proto::WireType::Fixed32",
                        "fixed64" | "double" => "proto::WireType::Fixed64",
                        _ => "proto::WireType::Varint",
                    };
                    let kind = scalar_kind(s);
                    out.push_str(&format!(
                        "{e}({n}, {wire}) => {{\n\
                         {e}    result.{f} = proto::conv_{kind}(value);\n\
                         {e}}}\n"
                    ));
                }
            }
            FieldType::Message(m) => out.push_str(&format!(
                "{e}({n}, proto::WireType::LengthDelimited) => {{\n\
                 {e}    result.{f} = Some(proto::decode_sub_message::<{m}>(payload)?);\n\
                 {e}}}\n"
            )),
            FieldType::Repeated(s) if *s == "string" => out.push_str(&format!(
                "{e}({n}, proto::WireType::LengthDelimited) => {{\n\
                 {e}    result.{f}.push(\n\
                 {e}        ::core::str::from_utf8(payload)\n\
                 {e}            .map_err(|_| Error::protocol(\"invalid utf8 in protobuf string\"))?\n\
                 {e}            .to_string(),\n\
                 {e}    );\n\
                 {e}}}\n"
            )),
            FieldType::Repeated(s) if *s == "bytes" => out.push_str(&format!(
                "{e}({n}, proto::WireType::LengthDelimited) => {{\n\
                 {e}    result.{f}.push(payload.to_vec());\n\
                 {e}}}\n"
            )),
            FieldType::Repeated(s) => {
                let kind = scalar_kind(s);
                // Accept both packed (LengthDelimited) and unpacked
                // (per-element wire type) encodings.
                let element_wire = match *s {
                    "fixed32" | "float" => "proto::WireType::Fixed32",
                    "fixed64" | "double" => "proto::WireType::Fixed64",
                    _ => "proto::WireType::Varint",
                };
                out.push_str(&format!(
                    "{e}({n}, proto::WireType::LengthDelimited) => {{\n\
                     {e}    for v in proto::decode_packed_{kind}(payload)? {{\n\
                     {e}        result.{f}.push(v);\n\
                     {e}    }}\n\
                     {e}}}\n\
                     {e}({n}, {element_wire}) => {{\n\
                     {e}    result.{f}.push(proto::conv_{kind}(value));\n\
                     {e}}}\n"
                ));
            }
            FieldType::RepeatedMessage(m) => out.push_str(&format!(
                "{e}({n}, proto::WireType::LengthDelimited) => {{\n\
                 {e}    result.{f}.push(proto::decode_sub_message::<{m}>(payload)?);\n\
                 {e}}}\n"
            )),
        }
    }
    out.push_str(&format!("{ind}                    _ => {{}}\n"));
    out.push_str(&format!("{ind}                }}\n"));
    out.push_str(&format!("{ind}                Ok(())\n"));
    out.push_str(&format!("{ind}            }})?;\n"));
    out.push_str(&format!("{ind}        }}\n"));
    out.push_str(&format!("{ind}        Ok(result)\n"));
    out.push_str(&format!("{ind}    }}\n"));
    out.push_str(&format!("{ind}}}\n"));

    // Codec trait impls.
    out.push_str(&format!(
        "\n{ind}impl codec::EncodeMessage for {} {{\n",
        message.name
    ));
    out.push_str(&format!(
        "{ind}    fn encode_message(&self) -> Result<alloc::vec::Vec<u8>> {{\n\
         {ind}        let mut out = alloc::vec::Vec::new();\n\
         {ind}        self.encode_message_body(&mut out);\n\
         {ind}        Ok(out)\n\
         {ind}    }}\n\
         {ind}}}\n"
    ));
    out.push_str(&format!(
        "\n{ind}impl codec::DecodeMessage for {} {{\n",
        message.name
    ));
    out.push_str(&format!(
        "{ind}    fn decode_message(bytes: &[u8]) -> Result<Self> {{\n\
         {ind}        Self::decode_message_body(bytes)\n\
         {ind}    }}\n\
         {ind}}}\n"
    ));
}

fn generate_service(out: &mut String, service: &Service, level: usize, package: Option<&str>) {
    let ind = indent(level);
    let qualified = match package {
        Some(pkg) => format!("/{pkg}.{}", service.name),
        None => format!("/{}", service.name),
    };
    let path = qualified.clone();
    out.push_str(&format!(
        "\n{ind}/// Generated gRPC client stub for service `{}`.\n",
        service.name
    ));
    out.push_str(&format!(
        "{ind}#[derive(Clone)]\n{ind}pub struct {} {{\n{ind}    inner: crate::courierust_grpc::GrpcClient,\n{ind}}}\n",
        service.name
    ));
    out.push_str(&format!("\n{ind}impl {} {{\n", service.name));
    out.push_str(&format!(
        "{ind}    /// Create a typed client stub bound to a gRPC connection.\n\
         {ind}    pub fn new(client: crate::courierust_grpc::GrpcClient) -> Self {{\n\
         {ind}        Self {{ inner: client }}\n\
         {ind}    }}\n"
    ));
    out.push_str(&format!(
        "{ind}    /// The fully-qualified service name.\n\
         {ind}    pub fn service_path(&self) -> &'static str {{\n\
         {ind}        \"{path}\"\n\
         {ind}    }}\n"
    ));
    for rpc in &service.rpcs {
        let method = to_snake(&rpc.name);
        let full = format!("{path}/{}", rpc.name);
        if rpc.server_streaming {
            out.push_str(&format!(
                "\n{ind}    /// Server-streaming RPC `{full}`: returns a stream of `{}` messages.\n\
                 {ind}    pub fn {method}(&self, request: {}) -> Result<crate::courierust_grpc::MessageStream> {{\n\
                 {ind}        let bytes = codec::EncodeMessage::encode_message(&request)?;\n\
                 {ind}        self.inner.call_stream(\"{full}\", bytes.into())\n\
                 {ind}    }}\n",
                rpc.response, rpc.request
            ));
        } else {
            out.push_str(&format!(
                "\n{ind}    /// Unary RPC `{full}`.\n\
                 {ind}    pub fn {method}(&self, request: {}) -> Result<{}> {{\n\
                 {ind}        self.inner.call_unary(\"{full}\", &request)\n\
                 {ind}    }}\n",
                rpc.request, rpc.response
            ));
        }
    }
    out.push_str(&format!("{ind}}}\n"));
}
