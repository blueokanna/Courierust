#!/usr/bin/env bash
set -euo pipefail

if [[ $# -ne 3 ]]; then
    printf 'usage: %s THROUGHPUT_LOG COMPARE_LOG OUTPUT\n' "$0" >&2
    exit 2
fi

throughput_log=$1
compare_log=$2
output=$3

extract_lines() {
    local pattern=$1
    local file=$2

    if [[ -s "$file" ]]; then
        grep -E "$pattern" "$file" || true
    fi
}

write_table() {
    local lines=$1
    local line
    local name
    local value

    if [[ -z "$lines" ]]; then
        printf '| _No benchmark result captured_ | |\n'
        return
    fi

    while IFS= read -r line; do
        [[ -z "$line" ]] && continue
        name=${line%%:*}
        value=${line#*: }
        value=${value//|/\\|}
        printf '| `%s` | %s |\n' "$name" "$value"
    done <<< "$lines"
}

# Render `RESULT|suite=throughput|case=...|rps=...|...|p50_us=..|p75_us=..|p90_us=..|p95_us=..|p99_us=..|...`
# lines as a latency table covering P50..P99.
write_result_table() {
    local lines=$1
    local line
    local field

    if [[ -z "$lines" ]]; then
        printf '| _No benchmark result captured_ |\n'
        return
    fi

    printf '| Case | RPS | resp MB/s | P50 µs | P75 µs | P90 µs | P95 µs | P99 µs |\n'
    printf '| --- | --- | --- | --- | --- | --- | --- | --- |\n'
    while IFS= read -r line; do
        [[ -z "$line" ]] && continue
        field() { printf '%s' "$line" | sed -n "s/.*$1=[^|]*//;s/.*$1=\([^|]*\).*/\1/p"; }
        local case_name
        local rps
        local mbps
        local p50
        local p75
        local p90
        local p95
        local p99
        case_name=$(field 'case')
        rps=$(field 'rps')
        mbps=$(field 'response_mbps')
        p50=$(field 'p50_us')
        p75=$(field 'p75_us')
        p90=$(field 'p90_us')
        p95=$(field 'p95_us')
        p99=$(field 'p99_us')
        printf '| `%s` | %s | %s | %s | %s | %s | %s | %s |\n' \
            "$case_name" "$rps" "$mbps" "$p50" "$p75" "$p90" "$p95" "$p99"
    done <<< "$lines"
}

write_raw_block() {
    local file=$1
    local pattern=$2

    if [[ -s "$file" ]]; then
        grep -E "$pattern" "$file" || true
    else
        printf 'No output was captured for this benchmark.\n'
    fi
}

sha=${GITHUB_SHA:-local}
run_id=${GITHUB_RUN_ID:-local}
ref=${GITHUB_REF_NAME:-local}
runner=${RUNNER_OS:-$(uname -s)}
throughput_status=${BENCHMARK_THROUGHPUT_EXIT:-not-recorded}
compare_status=${BENCHMARK_COMPARE_EXIT:-not-recorded}

throughput_results=$(extract_lines '^RESULT\|suite=throughput' "$throughput_log")
compare_results=$(extract_lines '^(raw_tcp_floor|h1 |h2 )[^:]*:' "$compare_log")

{
    printf '# GitHub Action Benchmark\n\n'
    printf 'Generated by the `benchmark.yml` workflow.\n\n'
    printf '%s\n' '## Run'
    printf '%s\n' ''
    printf -- '- Commit: `%s`\n' "$sha"
    printf -- '- Ref: `%s`\n' "$ref"
    printf -- '- Runner: `%s`\n' "$runner"
    printf -- '- Throughput exit code: `%s`\n' "$throughput_status"
    printf -- '- Comparison exit code: `%s`\n' "$compare_status"
    if [[ -n "${GITHUB_SERVER_URL:-}" && -n "${GITHUB_REPOSITORY:-}" && -n "${GITHUB_RUN_ID:-}" ]]; then
        printf -- '- Workflow run: [%s](%s/%s/actions/runs/%s)\n' "$run_id" "$GITHUB_SERVER_URL" "$GITHUB_REPOSITORY" "$GITHUB_RUN_ID"
    else
        printf -- '- Workflow run: `%s`\n' "$run_id"
    fi

    printf '\n%s\n\n' '## Throughput (P50–P99 latency)'
    write_result_table "$throughput_results"
    printf '\n'

    printf '%s\n\n' '## Cross-library comparison'
    printf '| Benchmark | Result |\n'
    printf '| --- | --- |\n'
    write_table "$compare_results"
    printf '\n'

    printf '%s\n\n' '## Captured Benchmark Output'
    printf '%s\n\n' '### Throughput'
    printf '%s\n' '```text'
    write_raw_block "$throughput_log" '^(courierust benchmarks|h1_|h2_|total:)'
    printf '%s\n\n' '```'
    printf '%s\n\n' '### Cross-library comparison'
    printf '%s\n' '```text'
    write_raw_block "$compare_log" '^(courierust vs mainstream|raw_tcp_floor|h1 |h2 )'
    printf '%s\n' '```'
} > "$output"

printf 'Wrote %s\n' "$output"
